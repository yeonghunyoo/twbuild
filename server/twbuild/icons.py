def expected(root, cfg=None):
    """{상대경로: 텍스트} — 지금 레이아웃 트리에서 나와야 하는 아이콘 코드. raw-svg 데이터가 있는 아이콘이 없으면 빈 dict."""
    icons, _ = collect(layouts(root))
    if not icons:
        return {}
    cfg = cfg or config.load(root)
    plats = cfg.get("platforms") or []
    out = {}
    if "ios" in plats:
        out[os.path.join(util.APPS["ios"], SWIFT_REL)] = swift(icons)
    if "android" in plats:
        pkg = config.app_vars(cfg)["id"]
        out[os.path.join(util.APPS["android"], KT_REL.replace("{pkg}", pkg.replace(".", "/")))] = kotlin(icons, pkg)
    return out


def write(root, cfg=None):
    files = expected(root, cfg)
    for rel, text in files.items():
        util.write_text(os.path.join(root, rel), text)
    return sorted(files)


def drift(root, cfg=None):
    return [rel for rel, text in expected(root, cfg).items() if util.read_text(os.path.join(root, rel), None) != text]


def cli(argv, root):
    """`twbuild icons` — 생성 아이콘을 쓰고 목록을 보인다 (한국어)."""
    try:
        icons, nodes = collect(layouts(root))
        files = write(root)
    except IconError as e:
        return 1, f"아이콘 생성 실패: {e}"
    if not icons:
        return 0, "경로 데이터가 있는 아이콘이 없다 (레이아웃 트리의 icon 노드에 svg 가 없다)."
    lines = [f"아이콘 {len(icons)}개 (노드 {len(nodes)}개에서, 같은 그림은 합침) → " + ", ".join(files)]
    for n, ic in icons.items():
        paint = ("fill" if ic["fill"] is True else "fill:bind" if ic["fill"] == "bind" else "") + (" stroke" if ic["stroke"] is True else " stroke:bind" if ic["stroke"] == "bind" else "")
        lines.append(f"  {n:<12} viewBox {ic['viewbox']:<12} {paint.strip():<18} {len(ic['nodes'])}곳  {ic['nodes'][0]}")
    return 0, "\n".join(lines)
