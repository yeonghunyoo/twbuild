class IconError(ValueError):
    pass


# ─────────────────────────── 경로 파서 ───────────────────────────

_CMDS = "MmLlHhVvCcSsQqTtAaZz"
_NUM = re.compile(r"[-+]?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?")
_ARGS = {"M": 2, "L": 2, "H": 1, "V": 1, "C": 6, "S": 4, "Q": 4, "T": 2, "A": 7, "Z": 0}


class _Scan:
    """경로 문자열 한 글자씩 — 숫자 사이 구분자가 없어도(`1.5.5` · `-1-2`) · 호 플래그가 붙어 있어도(`00`) 읽는다."""

    def __init__(self, d):
        self.d, self.i = d or "", 0

    def skip(self):
        while self.i < len(self.d) and (self.d[self.i].isspace() or self.d[self.i] == ","):
            self.i += 1

    def done(self):
        self.skip()
        return self.i >= len(self.d)

    def peek_cmd(self):
        self.skip()
        return self.d[self.i] if self.i < len(self.d) and self.d[self.i] in _CMDS else None

    def number(self):
        self.skip()
        m = _NUM.match(self.d, self.i)
        if not m:
            raise IconError(f"경로 숫자를 못 읽었다: {self.d[self.i:self.i + 12]!r}")
        self.i = m.end()
        return float(m.group(0))

    def flag(self):
        self.skip()
        c = self.d[self.i:self.i + 1]
        if c not in ("0", "1"):
            raise IconError(f"호 플래그는 0 · 1 이다: {self.d[self.i:self.i + 8]!r}")
        self.i += 1
        return c == "1"


def _angle(ux, uy, vx, vy):
    return math.atan2(ux * vy - uy * vx, ux * vx + uy * vy)


def arc_to_cubics(x1, y1, rx, ry, phi_deg, large, sweep, x2, y2):
    """SVG 호(끝점 표기) → 3차 베지어 목록 [("C", c1x, c1y, c2x, c2y, x, y)]. SVG 명세 F.6.5 · 조각당 90° 이하."""
    if abs(x1 - x2) < 1e-12 and abs(y1 - y2) < 1e-12:
        return []
    rx, ry = abs(rx), abs(ry)
    if rx < 1e-12 or ry < 1e-12:
        return [("L", x2, y2)]
    phi = math.radians(phi_deg % 360)
    c, s = math.cos(phi), math.sin(phi)
    dx2, dy2 = (x1 - x2) / 2, (y1 - y2) / 2
    x1p, y1p = c * dx2 + s * dy2, -s * dx2 + c * dy2
    lam = (x1p * x1p) / (rx * rx) + (y1p * y1p) / (ry * ry)
    if lam > 1:
        k = math.sqrt(lam)
        rx, ry = rx * k, ry * k
    num = rx * rx * ry * ry - rx * rx * y1p * y1p - ry * ry * x1p * x1p
    den = rx * rx * y1p * y1p + ry * ry * x1p * x1p
    coef = math.sqrt(max(0.0, num / den)) if den else 0.0
    if large == sweep:
        coef = -coef
    cxp, cyp = coef * rx * y1p / ry, -coef * ry * x1p / rx
    cx = c * cxp - s * cyp + (x1 + x2) / 2
    cy = s * cxp + c * cyp + (y1 + y2) / 2
    ux, uy = (x1p - cxp) / rx, (y1p - cyp) / ry
    vx, vy = (-x1p - cxp) / rx, (-y1p - cyp) / ry
    t1 = _angle(1, 0, ux, uy)
    dt = _angle(ux, uy, vx, vy)
    if not sweep and dt > 0:
        dt -= 2 * math.pi
    elif sweep and dt < 0:
        dt += 2 * math.pi
    n = max(1, int(math.ceil(abs(dt) / (math.pi / 2) - 1e-9)))
    delta = dt / n
    t = 4.0 / 3.0 * math.tan(delta / 4)

    def mp(ex, ey):                                  # 단위원 → 실제 타원 (회전 · 크기 · 중심)
        return cx + rx * c * ex - ry * s * ey, cy + rx * s * ex + ry * c * ey

    out = []
    for i in range(n):
        a1 = t1 + i * delta
        a2 = a1 + delta
        e1x, e1y, e2x, e2y = math.cos(a1), math.sin(a1), math.cos(a2), math.sin(a2)
        p1 = mp(e1x - t * e1y, e1y + t * e1x)
        p2 = mp(e2x + t * e2y, e2y - t * e2x)
        end = (x2, y2) if i == n - 1 else mp(e2x, e2y)
        out.append(("C", p1[0], p1[1], p2[0], p2[1], end[0], end[1]))
    return out


def parse_path(d):
    """SVG path `d` → 절대 좌표 명령 [("M",x,y) · ("L",x,y) · ("C",x1,y1,x2,y2,x,y) · ("Q",x1,y1,x,y) · ("Z",)]. 호는 3차 베지어로."""
    sc = _Scan(d)
    out = []
    cx = cy = sx = sy = 0.0
    prev = None                                     # 이전 명령 (S · T 의 제어점 반사용)
    last_c = last_q = None
    cmd = None
    while not sc.done():
        nc = sc.peek_cmd()
        if nc:
            cmd = nc
            sc.i += 1
        elif cmd is None:
            raise IconError(f"명령으로 시작하지 않는다: {d[:20]!r}")
        elif cmd in "Zz":
            raise IconError("Z 뒤에 숫자가 왔다")
        rel = cmd.islower()
        C = cmd.upper()
        if C == "Z":
            out.append(("Z",))
            cx, cy = sx, sy
            prev, last_c, last_q = "Z", None, None
            continue
        ox, oy = (cx, cy) if rel else (0.0, 0.0)
        if C == "M":
            x, y = sc.number() + ox, sc.number() + oy
            out.append(("M", x, y))
            cx, cy, sx, sy = x, y, x, y
            cmd = "l" if rel else "L"                  # 뒤따르는 좌표 쌍은 L (암묵 반복)
            prev, last_c, last_q = "M", None, None
            continue
        if C == "L":
            x, y = sc.number() + ox, sc.number() + oy
            out.append(("L", x, y))
            cx, cy = x, y
            last_c = last_q = None
        elif C == "H":
            x = sc.number() + (cx if rel else 0.0)
            out.append(("L", x, cy))
            cx = x
            last_c = last_q = None
        elif C == "V":
            y = sc.number() + (cy if rel else 0.0)
            out.append(("L", cx, y))
            cy = y
            last_c = last_q = None
        elif C == "C":
            x1, y1 = sc.number() + ox, sc.number() + oy
            x2, y2 = sc.number() + ox, sc.number() + oy
            x, y = sc.number() + ox, sc.number() + oy
            out.append(("C", x1, y1, x2, y2, x, y))
            last_c, last_q = (x2, y2), None
            cx, cy = x, y
        elif C == "S":
            x1, y1 = (2 * cx - last_c[0], 2 * cy - last_c[1]) if last_c else (cx, cy)
            x2, y2 = sc.number() + ox, sc.number() + oy
            x, y = sc.number() + ox, sc.number() + oy
            out.append(("C", x1, y1, x2, y2, x, y))
            last_c, last_q = (x2, y2), None
            cx, cy = x, y
        elif C == "Q":
            x1, y1 = sc.number() + ox, sc.number() + oy
            x, y = sc.number() + ox, sc.number() + oy
            out.append(("Q", x1, y1, x, y))
            last_q, last_c = (x1, y1), None
            cx, cy = x, y
        elif C == "T":
            x1, y1 = (2 * cx - last_q[0], 2 * cy - last_q[1]) if last_q else (cx, cy)
            x, y = sc.number() + ox, sc.number() + oy
            out.append(("Q", x1, y1, x, y))
            last_q, last_c = (x1, y1), None
            cx, cy = x, y
        elif C == "A":
            rx, ry, phi = sc.number(), sc.number(), sc.number()
            large, sweep = sc.flag(), sc.flag()
            x, y = sc.number() + ox, sc.number() + oy
            out.extend(arc_to_cubics(cx, cy, rx, ry, phi, large, sweep, x, y))
            cx, cy = x, y
            last_c = last_q = None
        prev = C
    return out


def _attrs_of(spec):
    """`circle(cx=12 cy=12 r=9)` → ("circle", {"cx": "12", …}). points 값의 공백도 견딘다."""
    m = re.match(r"^(\w+)\((.*)\)$", spec.strip(), re.S)
    if not m:
        return None, {}
    parts = re.split(r"\s+(?=[\w-]+=)", m.group(2).strip())
    out = {}
    for p in parts:
        if "=" in p:
            k, v = p.split("=", 1)
            out[k.strip()] = v.strip().strip('"\'')
    return m.group(1), out


def _f(a, k, default=0.0):
    v = a.get(k)
    if v is None or str(v).strip() in ("", "auto"):
        return default
    try:
        return float(re.sub(r"(px)?$", "", str(v).strip()))
    except ValueError:
        return default


def parse_shape(spec):
    """도형 문자열(tree 가 남긴 circle(...) · ellipse · rect · line · polyline · polygon) → 경로 명령."""
    tag, a = _attrs_of(spec)
    if tag in ("circle", "ellipse"):
        cx, cy = _f(a, "cx"), _f(a, "cy")
        rx = _f(a, "r") if tag == "circle" else _f(a, "rx")
        ry = _f(a, "r") if tag == "circle" else _f(a, "ry")
        if rx <= 0 or ry <= 0:
            return []
        out = [("M", cx + rx, cy)]
        out += arc_to_cubics(cx + rx, cy, rx, ry, 0, False, True, cx - rx, cy)
        out += arc_to_cubics(cx - rx, cy, rx, ry, 0, False, True, cx + rx, cy)
        return out + [("Z",)]
    if tag == "rect":
        x, y, w, h = _f(a, "x"), _f(a, "y"), _f(a, "width"), _f(a, "height")
        if w <= 0 or h <= 0:
            return []
        rx, ry = a.get("rx"), a.get("ry")
        rx = _f(a, "rx") if rx is not None else (_f(a, "ry") if ry is not None else 0.0)
        ry = _f(a, "ry") if ry is not None else rx
        rx, ry = min(rx, w / 2), min(ry, h / 2)
        if rx <= 0 or ry <= 0:
            return [("M", x, y), ("L", x + w, y), ("L", x + w, y + h), ("L", x, y + h), ("Z",)]
        out = [("M", x + rx, y), ("L", x + w - rx, y)]
        out += arc_to_cubics(x + w - rx, y, rx, ry, 0, False, True, x + w, y + ry)
        out += [("L", x + w, y + h - ry)]
        out += arc_to_cubics(x + w, y + h - ry, rx, ry, 0, False, True, x + w - rx, y + h)
        out += [("L", x + rx, y + h)]
        out += arc_to_cubics(x + rx, y + h, rx, ry, 0, False, True, x, y + h - ry)
        out += [("L", x, y + ry)]
        out += arc_to_cubics(x, y + ry, rx, ry, 0, False, True, x + rx, y)
        return out + [("Z",)]
    if tag == "line":
        return [("M", _f(a, "x1"), _f(a, "y1")), ("L", _f(a, "x2"), _f(a, "y2"))]
    if tag in ("polyline", "polygon"):
        nums = [float(x) for x in _NUM.findall(a.get("points", ""))]
        pts = list(zip(nums[0::2], nums[1::2]))
        if not pts:
            return []
        out = [("M", pts[0][0], pts[0][1])] + [("L", px, py) for px, py in pts[1:]]
        return out + ([("Z",)] if tag == "polygon" else [])
    raise IconError(f"모르는 도형: {spec[:40]!r}")


def commands_of(entry):
    """트리 svg 항목 하나(경로 d 또는 도형 문자열) → 명령."""
    if re.match(r"^(circle|ellipse|rect|line|polyline|polygon)\(", entry.strip()):
        return parse_shape(entry)
    return parse_path(entry)


