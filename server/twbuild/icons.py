def viewbox_of(node):
    vb = str(node.get("viewbox") or "").strip()
    nums = [float(x) for x in _NUM.findall(vb)]
    if len(nums) == 4 and nums[2] > 0 and nums[3] > 0:
        return tuple(nums)
    w, h = _f(node, "width", 0.0), _f(node, "height", 0.0)
    if w > 0 and h > 0:
        return (0.0, 0.0, w, h)
    return DEFAULT_VIEWBOX


def paint_of(node):
    """칠 방식(색 제외) — fill · stroke 는 True · False · "bind"(상태가 정한다). SVG 기본값: fill 검정(켜짐) · stroke 없음."""
    p = node.get("svg_paint") or {}

    def mode(v, default):
        if v is None:
            return default
        v = str(v).strip().lower()
        if v.startswith("bind:"):
            return "bind"
        return v not in ("none", "transparent")

    try:
        sw = float(re.sub(r"px$", "", str(p.get("stroke-width", "1")).strip()))
    except ValueError:
        sw = 1.0
    cap = str(p.get("stroke-linecap", "butt")).strip().lower()
    join = str(p.get("stroke-linejoin", "miter")).strip().lower()
    return {"fill": mode(p.get("fill"), True), "stroke": mode(p.get("stroke"), False), "stroke_width": sw,
            "linecap": cap if cap in ("butt", "round", "square") else "butt",
            "linejoin": join if join in ("miter", "round", "bevel") else "miter",
            "fill_rule": "evenodd" if str(p.get("fill-rule", "")).strip().lower() == "evenodd" else "nonzero"}


def name_of(node):
    """icon 노드 → 생성 아이콘 이름 `ic<해시>` (svg 가 없으면 None). 결정적 — 생성기 · 초안 · 게이트(T11)가 같은 함수를 쓴다."""
    svg = node.get("svg") or []
    if not svg:
        return None
    key = util.stable_json({"svg": list(svg), "viewbox": list(viewbox_of(node)), "paint": paint_of(node)})
    h = util.sha_text(key)[:8]
    return "ic" + h[0].upper() + h[1:]


def _walk(n, out):
    if not isinstance(n, dict):
        return
    if n.get("kind") == "icon" and n.get("svg"):
        out.append(n)
    for c in n.get("children") or []:
        _walk(c, out)


def collect(lays):
    """레이아웃 트리들 → ({이름: 아이콘 spec}, {노드 ID: 이름}). lays: {화면: 트리} 또는 트리 목록. 같은 아이콘은 하나로."""
    trees = list(lays.values()) if isinstance(lays, dict) else list(lays or [])
    icons, nodes = {}, {}
    for lay in trees:
        found = []
        _walk((lay or {}).get("root"), found)
        for n in found:
            name = name_of(n)
            nodes[n.get("id")] = name
            if name in icons:
                icons[name]["nodes"].append(n.get("id"))
                continue
            try:
                cmds = [commands_of(e) for e in n["svg"]]
            except IconError as e:
                raise IconError(f"{n.get('id')}: {e}")
            icons[name] = {"svg": list(n["svg"]), "viewbox": " ".join(_num(v) for v in viewbox_of(n)), "commands": cmds,
                           **paint_of(n), "nodes": [n.get("id")]}
    for v in icons.values():
        v["nodes"] = sorted(x for x in v["nodes"] if x)
    return dict(sorted(icons.items())), dict(sorted((k, v) for k, v in nodes.items() if k))


def layouts(root):
    """모든 기능의 레이아웃 트리 — design/<기능>/layout/*.json."""
    out = {}
    d = os.path.join(root, util.DESIGN_DIR)
    if not os.path.isdir(d):
        return out
    for feat in sorted(os.listdir(d)):
        ld = os.path.join(d, feat, "layout")
        if feat == "ds" or not os.path.isdir(ld):
            continue
        for n in sorted(os.listdir(ld)):
            if n.endswith(".json"):
                lay = util.read_json(os.path.join(ld, n), None)
                if lay:
                    out[f"{feat}/{n[:-5]}"] = lay
    return out


