def _num(x):
    s = f"{round(x, 4):.4f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def _kf(x):
    return _num(x) + "f"


def _shift(cmds, vb):
    """viewBox 원점이 0 이 아니면 좌표를 옮긴다 (ImageVector 에는 원점 개념이 없다)."""
    ox, oy = vb[0], vb[1]
    if not ox and not oy:
        return cmds
    out = []
    for c in cmds:
        vals = list(c[1:])
        out.append((c[0], *[v - (ox if i % 2 == 0 else oy) for i, v in enumerate(vals)]))
    return out


_SWIFT_CAP = {"butt": ".butt", "round": ".round", "square": ".square"}
_SWIFT_JOIN = {"miter": ".miter", "round": ".round", "bevel": ".bevel"}
_KT_CAP = {"butt": "StrokeCap.Butt", "round": "StrokeCap.Round", "square": "StrokeCap.Square"}
_KT_JOIN = {"miter": "StrokeJoin.Miter", "round": "StrokeJoin.Round", "bevel": "StrokeJoin.Bevel"}


def _default(mode, fallback):
    return mode if isinstance(mode, bool) else fallback


def _bind_defaults(ic):
    """바인딩 칠의 기본값 — fill 은 꺼짐, stroke 는 선 굵기가 적혀 있으면 켜짐. 호출부가 상태로 바꾼다."""
    fill = _default(ic["fill"], False)
    stroke = _default(ic["stroke"], True)
    if not fill and not stroke:
        fill = True
    return fill, stroke


def swift(icons):
    """Icons.swift — enum TwIcon(경로) · TwIconShape(Shape) · TwIconView(칠/선, 호출부 foregroundStyle 이 색)."""
    L = [f"// {HEADER}", "// Same icons, same names as Android TwIcons (gate T11). Tint with .foregroundStyle(...) at the call site.", "",
         "import SwiftUI", "",
         "enum TwIconCap: Sendable { case butt, round, square }",
         "enum TwIconJoin: Sendable { case miter, round, bevel }", "",
         "struct TwIconPaint: Sendable {",
         "    let fill: Bool", "    let stroke: Bool", "    let strokeWidth: CGFloat", "    let cap: TwIconCap", "    let join: TwIconJoin", "    let evenOdd: Bool",
         "}", "",
         "enum TwIcon: String, CaseIterable, Sendable {"]
    if icons:
        L += [f"    case {n}" for n in icons]
    else:
        L += ["    case none"]
    L += ["", "    /// viewBox width · height (origin already moved to 0,0)", "    var viewSize: CGSize {", "        switch self {"]
    for n, ic in icons.items():
        vb = [float(v) for v in ic["viewbox"].split()]
        L.append(f"        case .{n}: return CGSize(width: {_num(vb[2])}, height: {_num(vb[3])})")
    if not icons:
        L.append("        case .none: return CGSize(width: 24, height: 24)")
    L += ["        }", "    }", "", "    var paint: TwIconPaint {", "        switch self {"]
    for n, ic in icons.items():
        fill, stroke = _bind_defaults(ic)
        L.append(f"        case .{n}: return TwIconPaint(fill: {str(fill).lower()}, stroke: {str(stroke).lower()}, strokeWidth: {_num(ic['stroke_width'])}, "
                 f"cap: {_SWIFT_CAP[ic['linecap']]}, join: {_SWIFT_JOIN[ic['linejoin']]}, evenOdd: {str(ic['fill_rule'] == 'evenodd').lower()})")
    if not icons:
        L.append("        case .none: return TwIconPaint(fill: true, stroke: false, strokeWidth: 1, cap: .butt, join: .miter, evenOdd: false)")
    L += ["        }", "    }", "",
          "    /// Draws the icon in viewBox units through `t` (viewBox point → rect point).",
          "    func draw(into p: inout Path, _ t: (CGFloat, CGFloat) -> CGPoint) {", "        switch self {"]
    for n, ic in icons.items():
        vb = [float(v) for v in ic["viewbox"].split()]
        L.append(f"        case .{n}:  // {', '.join(ic['nodes'][:4])}{' …' if len(ic['nodes']) > 4 else ''}")
        for cmds in ic["commands"]:
            for c in _shift(cmds, vb):
                if c[0] == "M":
                    L.append(f"            p.move(to: t({_num(c[1])}, {_num(c[2])}))")
                elif c[0] == "L":
                    L.append(f"            p.addLine(to: t({_num(c[1])}, {_num(c[2])}))")
                elif c[0] == "C":
                    L.append(f"            p.addCurve(to: t({_num(c[5])}, {_num(c[6])}), control1: t({_num(c[1])}, {_num(c[2])}), control2: t({_num(c[3])}, {_num(c[4])}))")
                elif c[0] == "Q":
                    L.append(f"            p.addQuadCurve(to: t({_num(c[3])}, {_num(c[4])}), control: t({_num(c[1])}, {_num(c[2])}))")
                elif c[0] == "Z":
                    L.append("            p.closeSubpath()")
        if not any(ic["commands"]):
            L.append("            break")
    if not icons:
        L.append("        case .none: break")
    L += ["        }", "    }", "}", "",
          "struct TwIconShape: Shape {",
          "    let icon: TwIcon", "",
          "    func path(in rect: CGRect) -> Path {",
          "        let v = icon.viewSize",
          "        let s = min(rect.width / v.width, rect.height / v.height)",
          "        let dx = rect.minX + (rect.width - v.width * s) / 2",
          "        let dy = rect.minY + (rect.height - v.height * s) / 2",
          "        var p = Path()",
          "        icon.draw(into: &p) { x, y in CGPoint(x: dx + x * s, y: dy + y * s) }",
          "        return p",
          "    }",
          "}", "",
          "/// A generated icon at `size` points wide. `fill` / `stroke` override the design's paint when the design binds it to state.",
          "struct TwIconView: View {",
          "    let icon: TwIcon", "    let size: CGFloat", "    var fill: Bool? = nil", "    var stroke: Bool? = nil", "",
          "    init(_ icon: TwIcon, size: CGFloat, fill: Bool? = nil, stroke: Bool? = nil) {",
          "        self.icon = icon", "        self.size = size", "        self.fill = fill", "        self.stroke = stroke", "    }", "",
          "    var body: some View {",
          "        let paint = icon.paint",
          "        let v = icon.viewSize",
          "        let scale = size / v.width",
          "        ZStack {",
          "            if fill ?? paint.fill {",
          "                TwIconShape(icon: icon).fill(style: FillStyle(eoFill: paint.evenOdd))",
          "            }",
          "            if stroke ?? paint.stroke {",
          "                TwIconShape(icon: icon).stroke(style: StrokeStyle(lineWidth: paint.strokeWidth * scale, lineCap: paint.cap.cg, lineJoin: paint.join.cg))",
          "            }",
          "        }",
          "        .frame(width: size, height: size * v.height / v.width)",
          "    }",
          "}", "",
          "extension TwIconCap {",
          "    var cg: CGLineCap {", "        switch self {", "        case .butt: return .butt", "        case .round: return .round", "        case .square: return .square", "        }", "    }",
          "}", "",
          "extension TwIconJoin {",
          "    var cg: CGLineJoin {", "        switch self {", "        case .miter: return .miter", "        case .round: return .round", "        case .bevel: return .bevel", "        }", "    }",
          "}", ""]
    return "\n".join(L)


def kotlin(icons, pkg):
    """Icons.kt — object TwIcons { val icXxx: ImageVector } (+ icXxxWith(fill, stroke) — 상태가 칠을 바꾸는 아이콘용). 호출부 Icon(tint =) 이 색."""
    L = [f"// {HEADER}", "// Same icons, same names as iOS TwIcon (gate T11). Tint with Icon(TwIcons.icXxx, contentDescription, tint = ...).", "",
         f"package {pkg}.core.designsystem.generated", "",
         "import androidx.compose.ui.graphics.Color",
         "import androidx.compose.ui.graphics.PathFillType",
         "import androidx.compose.ui.graphics.SolidColor",
         "import androidx.compose.ui.graphics.StrokeCap",
         "import androidx.compose.ui.graphics.StrokeJoin",
         "import androidx.compose.ui.graphics.vector.ImageVector",
         "import androidx.compose.ui.graphics.vector.path",
         "import androidx.compose.ui.unit.dp", "",
         "object TwIcons {"]
    for n, ic in icons.items():
        vb = [float(v) for v in ic["viewbox"].split()]
        fill, stroke = _bind_defaults(ic)
        L += [f"    /** {', '.join(ic['nodes'][:4])}{' …' if len(ic['nodes']) > 4 else ''} */",
              f"    val {n}: ImageVector by lazy {{ {n}With(fill = {str(fill).lower()}, stroke = {str(stroke).lower()}) }}", "",
              f"    /** Paint override for states the design binds (build once and remember it). */",
              f"    fun {n}With(fill: Boolean, stroke: Boolean): ImageVector = ImageVector.Builder(",
              f"        name = \"{n}\", defaultWidth = {_num(vb[2])}.dp, defaultHeight = {_num(vb[3])}.dp, viewportWidth = {_kf(vb[2])}, viewportHeight = {_kf(vb[3])},",
              "    ).apply {"]
        for cmds in ic["commands"]:
            L += ["        path(",
                  "            fill = if (fill) SolidColor(Color.Black) else null,",
                  "            stroke = if (stroke) SolidColor(Color.Black) else null,",
                  f"            strokeLineWidth = {_kf(ic['stroke_width'])},",
                  f"            strokeLineCap = {_KT_CAP[ic['linecap']]},",
                  f"            strokeLineJoin = {_KT_JOIN[ic['linejoin']]},",
                  f"            pathFillType = {'PathFillType.EvenOdd' if ic['fill_rule'] == 'evenodd' else 'PathFillType.NonZero'},",
                  "        ) {"]
            for c in _shift(cmds, vb):
                if c[0] == "M":
                    L.append(f"            moveTo({_kf(c[1])}, {_kf(c[2])})")
                elif c[0] == "L":
                    L.append(f"            lineTo({_kf(c[1])}, {_kf(c[2])})")
                elif c[0] == "C":
                    L.append(f"            curveTo({', '.join(_kf(v) for v in c[1:])})")
                elif c[0] == "Q":
                    L.append(f"            quadTo({', '.join(_kf(v) for v in c[1:])})")
                elif c[0] == "Z":
                    L.append("            close()")
            L.append("        }")
        L += ["    }.build()", ""]
    if L[-1] == "":
        L.pop()
    L += ["}", ""]
    return "\n".join(L)


