"""아이콘 연결 — 레이아웃 트리의 raw-svg 아이콘(icon 노드의 svg · svg_paint)을 두 플랫폼 같은 벡터 아이콘 코드로 만든다 (AGENT.md 3장 · 6장 T11).

  apps/ios/App/Core/DesignSystem/Generated/Icons.swift                     enum TwIcon · TwIconShape · TwIconView(.icXxx, size:)
  apps/android/app/src/main/kotlin/<pkg>/core/designsystem/generated/Icons.kt   object TwIcons { val icXxx: ImageVector }

실측 동기: 같은 즐겨찾기 아이콘을 iOS 는 별, Android 는 하트로 그렸다(개발자가 추측). 이제 개발자는 raw-svg 아이콘을 손으로 그리지 않는다.
경로는 하네스가 미리 절대 좌표 M · L · C · Q · Z 로 정규화한다(호 → 3차 베지어). 런타임에 SVG 문자열을 파싱하지 않는다.
이름은 (svg, viewBox, 칠 방식)의 짧은 해시 — 같은 입력 = 같은 이름, 같은 아이콘은 하나로 합친다. 색은 이름에 들어가지 않는다(호출부가 tint).
표준 라이브러리만.
"""
