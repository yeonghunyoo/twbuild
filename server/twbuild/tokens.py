"""토큰 — 정본 design/ds/styles.css 의 :root CSS 변수에서 생성한다 (AGENT.md 1장). 생성물은 손으로 고치지 않는다.

  design/ds/tokens.json                                         중간 표현 (같은 입력 = 같은 바이트)
  apps/ios/App/Core/DesignSystem/Generated/Tokens.swift         Tokens.Color.accent400 · Tokens.Space.s1 · Tokens.Radius.sm · Tokens.Font.heading
  apps/android/.../core/designsystem/generated/Tokens.kt         같은 이름

못 잼(var() · color-mix() 같은 파생 값)은 raw 문자열로 싣고 unresolved 에 적는다 — 번역은 <플랫폼>-translate 가 한다.
"""
import os
import re

from . import config, util

CSS = os.path.join(util.DESIGN_DIR, "ds", "styles.css")
JSON = os.path.join(util.DESIGN_DIR, "ds", "tokens.json")
SWIFT_REL = os.path.join("App", "Core", "DesignSystem", "Generated", "Tokens.swift")
KT_REL = os.path.join("app", "src", "main", "kotlin", "{pkg}", "core", "designsystem", "generated", "Tokens.kt")

GROUPS = ("color", "space", "radius", "font", "shadow", "other")
_ROOT = re.compile(r":root\s*\{(.*?)\}", re.S)
_COMMENT = re.compile(r"/\*.*?\*/", re.S)
_VAR = re.compile(r"--([\w-]+)\s*:\s*([^;]+);")
_HEX = re.compile(r"^#([0-9a-fA-F]{3,8})$")
_PX = re.compile(r"^(-?\d+(?:\.\d+)?)px$")
_RGBA = re.compile(r"^rgba?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*(?:,\s*([\d.]+)\s*)?\)$")
_NUM = re.compile(r"^-?\d+(?:\.\d+)?$")
_FONT = re.compile(r'^"([^"]+)"|^\'([^\']+)\'')


def parse_vars(css):
    """:root 블록(들)의 --변수 → 값. 주석은 뺀다. 순서 유지."""
    out = {}
    for block in _ROOT.findall(_COMMENT.sub("", css or "")):
        for m in _VAR.finditer(block):
            out[m.group(1)] = m.group(2).strip()
    return out


def _group(name):
    for g in ("color", "space", "radius", "font", "shadow"):
        if name == g or name.startswith(g + "-"):
            return g, name[len(g) + 1:] or g
    return "other", name


def _hex6(h):
    """#rgb · #rgba · #rrggbb · #rrggbbaa → (#rrggbb, alpha)."""
    h = h.lower()
    if len(h) in (3, 4):
        h = "".join(c * 2 for c in h)
    rgb, a = h[:6], h[6:8]
    return "#" + rgb, round(int(a, 16) / 255, 3) if a else 1.0


def classify(value):
    v = value.strip()
    m = _HEX.match(v)
    if m and len(m.group(1)) in (3, 4, 6, 8):
        hx, a = _hex6(m.group(1))
        return {"kind": "color", "hex": hx, "alpha": a}
    m = _RGBA.match(v)
    if m:
        r, g, b = (min(255, int(m.group(i))) for i in (1, 2, 3))
        return {"kind": "color", "hex": "#%02x%02x%02x" % (r, g, b), "alpha": float(m.group(4)) if m.group(4) else 1.0}
    m = _PX.match(v)
    if m:
        return {"kind": "dimension", "px": float(m.group(1))}
    if _NUM.match(v):
        return {"kind": "number", "value": float(v) if "." in v else int(v)}
    m = _FONT.match(v)
    if m:
        fam = m.group(1) or m.group(2)
        rest = v[m.end():].lstrip(", ").strip()
        return {"kind": "font", "family": fam, "fallback": rest}
    return {"kind": "raw", "value": v, "unresolved": ("var(" in v or "color-mix(" in v or "calc(" in v)}


def tokens(css):
    """{"color": {이름: 항목}, "space": …, "unresolved": [이름], "source_sha": …}"""
    out = {g: {} for g in GROUPS}
    out["unresolved"] = []
    for name, val in parse_vars(css).items():
        g, short = _group(name)
        entry = classify(val)
        entry["var"] = name
        out[g][short] = entry
        if entry.get("unresolved"):
            out["unresolved"].append(name)
    out["source_sha"] = util.sha_text(css or "")[:12]
    return out


def ident(short):
    """CSS 변수 조각 → 코드 식별자. 'accent-2-400' → 'accent2_400', 'neutral-100' → 'neutral100', '1' → 's1', 'heading-weight' → 'headingWeight'."""
    parts = [p for p in re.split(r"[^0-9A-Za-z]+", short) if p]
    if not parts:
        return "x"
    out = parts[0]
    for prev, p in zip(parts, parts[1:]):
        if p[0].isdigit() and prev[-1].isdigit():
            out += "_" + p
        elif p[0].isdigit():
            out += p
        else:
            out += p[:1].upper() + p[1:]
    if out[0].isdigit():
        out = "s" + out
    return out


def const(group, short):
    """토큰 상수 이름 — 트리의 style 값 · 두 플랫폼 코드에 같은 이름이 쓰인다."""
    return f"Tokens.{group.capitalize()}.{ident(short)}"


# ─────────────────────────── 코드 생성 ───────────────────────────

def _swift_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def swift(tk):
    L = ["import SwiftUI", "",
         f"/// Design tokens — GENERATED by twbuild from design/ds/styles.css (sha {tk.get('source_sha', '')}). Do not edit.",
         "/// Raw entries (`Tokens.Shadow`, `Tokens.Other`) are CSS text the platform translator interprets.",
         "enum Tokens {"]
    for g in GROUPS:
        items = tk.get(g) or {}
        if not items:
            continue
        L.append(f"    enum {g.capitalize()} {{")
        for short, e in items.items():
            name = ident(short)
            k = e.get("kind")
            if k == "color":
                arg = f"0x{e['hex'][1:].upper()}" + (f", alpha: {e['alpha']}" if e.get("alpha", 1.0) != 1.0 else "")
                L.append(f"        static let {name} = SwiftUI.Color(twHex: {arg})")
            elif k == "dimension":
                L.append(f"        static let {name}: CGFloat = {e['px']:g}")
            elif k == "number":
                L.append(f"        static let {name}: Double = {e['value']}")
            elif k == "font":
                L.append(f"        static let {name} = {_swift_str(e['family'])}")
            else:
                L.append(f"        static let {name} = {_swift_str(e['value'])}" + ("   // unresolved" if e.get("unresolved") else ""))
        L.append("    }")
    L += ["}", "",
          "extension SwiftUI.Color {",
          "    init(twHex: UInt32, alpha: Double = 1) {",
          "        self.init(.sRGB, red: Double((twHex >> 16) & 0xFF) / 255, green: Double((twHex >> 8) & 0xFF) / 255,",
          "                  blue: Double(twHex & 0xFF) / 255, opacity: alpha)",
          "    }",
          "}", ""]
    return "\n".join(L)


def kotlin(tk, pkg):
    L = [f"package {pkg}.core.designsystem.generated", "", "import androidx.compose.ui.unit.dp", "",
         f"/** Design tokens — GENERATED by twbuild from design/ds/styles.css (sha {tk.get('source_sha', '')}). Do not edit. */",
         "object Tokens {"]
    for g in GROUPS:
        items = tk.get(g) or {}
        if not items:
            continue
        L.append(f"    object {g.capitalize()} {{")
        for short, e in items.items():
            name = ident(short)
            k = e.get("kind")
            if k == "color":
                a = int(round(e.get("alpha", 1.0) * 255))
                L.append(f"        val {name} = androidx.compose.ui.graphics.Color(0x{a:02X}{e['hex'][1:].upper()})")
            elif k == "dimension":
                L.append(f"        val {name} = {e['px']:g}.dp")
            elif k == "number":
                L.append(f"        const val {name} = {e['value']}")
            elif k == "font":
                L.append(f"        const val {name} = {_swift_str(e['family'])}")
            else:
                L.append(f"        const val {name} = {_swift_str(e['value'])}" + ("   // unresolved" if e.get("unresolved") else ""))
        L.append("    }")
    L += ["}", ""]
    return "\n".join(L)


# ─────────────────────────── 생성물 ───────────────────────────

def load(root):
    """tokens.json 이 있으면 그것, 없으면 styles.css 에서 바로. 둘 다 없으면 None."""
    css = util.read_text(os.path.join(root, CSS), None)
    return tokens(css) if css is not None else None


def expected(root, cfg=None):
    """{상대경로: 텍스트} — 지금 styles.css 에서 나와야 하는 생성물. styles.css 가 없으면 빈 dict."""
    css = util.read_text(os.path.join(root, CSS), None)
    if css is None:
        return {}
    cfg = cfg or config.load(root)
    tk = tokens(css)
    out = {JSON: util.stable_json(tk)}
    plats = cfg.get("platforms") or []
    if "ios" in plats:
        out[os.path.join(util.APPS["ios"], SWIFT_REL)] = swift(tk)
    if "android" in plats:
        pkg = config.app_vars(cfg)["id"]
        out[os.path.join(util.APPS["android"], KT_REL.replace("{pkg}", pkg.replace(".", "/")))] = kotlin(tk, pkg)
    return out


def write(root, cfg=None):
    files = expected(root, cfg)
    for rel, text in files.items():
        util.write_text(os.path.join(root, rel), text)
    return sorted(files)


def drift(root, cfg=None):
    return [rel for rel, text in expected(root, cfg).items() if util.read_text(os.path.join(root, rel), None) != text]
