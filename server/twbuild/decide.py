"""결정 — `twbuild decide <노드 ID> "<해석>" --by ios` (AGENT.md 5장). 결정은 이 명령으로만 기록한다.

원장 .twbuild/decisions.json (gitignore 아님 — 커밋되는 .claude/rules/team/<기능>.md 를 여기서 생성한다; 원장도 커밋 대상이라 .twbuild 밖에 둔다:
  .claude/rules/team/_decisions.json)
워크트리 안에서 불려도 git common dir 로 메인 레포 루트에 쓴다 — 워크트리의 rules 는 브랜치 시점 사본이라서다 (PoC 3).
같은 주제(노드 ID)가 이미 있으면 새로 쓰지 않고 기존 결정을 돌려준다 — 먼저 쓴 쪽이 이긴다. lead 가 확정(confirm)하거나 뒤집는다(flip).
"""
import os
import re

from . import design, git, util

LEDGER = os.path.join(".claude", "rules", "team", "_decisions.json")


class DecideError(ValueError):
    pass


def main_root(cwd):
    root = git.main_root(cwd)
    if not root or not util.is_wired(root):
        raise DecideError("twbuild 레포(또는 그 워크트리) 안에서 실행한다")
    return root


def ledger(root):
    return util.read_json(os.path.join(root, LEDGER), {"decisions": []}) or {"decisions": []}


def _save(root, led):
    util.write_json(os.path.join(root, LEDGER), led)
    for feature in sorted({d["feature"] for d in led["decisions"]}):
        util.write_text(os.path.join(root, ".claude", "rules", "team", f"{feature}.md"), render(feature, [d for d in led["decisions"] if d["feature"] == feature]))


def feature_of(root, topic):
    """노드 ID n.<화면>… → 원장의 기능. 모르면 'general'."""
    m = re.match(r"^n\.([A-Za-z0-9_-]+)", topic or "")
    if m:
        for key in design.index(root)["screens"]:
            feat, sid = key.split("/", 1)
            if sid == m.group(1):
                return feat, sid
    return "general", None


def record(cwd, topic, text, by):
    """새 결정(잠정). 같은 주제가 있으면 (기존, False)."""
    root = main_root(cwd)
    if not topic or not text or by not in ("ios", "android", "lead"):
        raise DecideError('decide <노드 ID> "<해석>" --by ios|android|lead')
    led = ledger(root)
    for d in led["decisions"]:
        if d["topic"] == topic and d["status"] != "flipped":
            return root, d, False
    feature, screen = feature_of(root, topic)
    did = f"D-{len(led['decisions']) + 1:02d}"
    d = {"id": did, "topic": topic, "text": text.strip(), "by": by, "t": util.now(), "feature": feature, "screen": screen, "status": "tentative"}
    led["decisions"].append(d)
    _save(root, led)
    return root, d, True


def confirm(cwd, did):
    root = main_root(cwd)
    led = ledger(root)
    for d in led["decisions"]:
        if d["id"] == did:
            d["status"] = "confirmed"
            d["confirmed_t"] = util.now()
            _save(root, led)
            return d
    raise DecideError(f"없는 결정: {did}")


def flip(cwd, did, text, by="lead"):
    """뒤집기 — 옛 결정은 flipped 로 남기고 같은 주제의 새 결정을 확정으로 쓴다."""
    root = main_root(cwd)
    led = ledger(root)
    old = next((d for d in led["decisions"] if d["id"] == did), None)
    if not old:
        raise DecideError(f"없는 결정: {did}")
    old["status"] = "flipped"
    new = {**old, "id": f"D-{len(led['decisions']) + 1:02d}", "text": text.strip(), "by": by, "t": util.now(), "status": "confirmed", "flips": did}
    led["decisions"].append(new)
    _save(root, led)
    return new


def since(root, feature, t_iso):
    """t_iso 이후에 생긴(또는 바뀐) 결정 — 훅 주입의 재료."""
    out = []
    for d in ledger(root)["decisions"]:
        if d["feature"] in (feature, "general") and d["status"] != "flipped" and max(d["t"], d.get("confirmed_t", "")) > (t_iso or ""):
            out.append(d)
    return out


def render(feature, decisions):
    """.claude/rules/team/<기능>.md — 경로 스코프 rule (에이전트용 영어). 생성물."""
    F = util.pascal(feature)
    feat = re.sub(r"[^a-z0-9]", "", feature.lower())
    lines = ["---",
             f"paths: [\"apps/ios/App/Features/{F}/**\", \"apps/android/**/features/{feat}/**\", \"design/{feature}/**\", \".twbuild/plans/{feature}/**\"]",
             "---", "",
             f"# Team decisions — {feature}", "",
             "Generated by `twbuild decide`. Do not edit by hand. A decision applies to its node (topic) on both platforms.",
             "`tentative` was recorded by one developer mid-build and binds the other until the lead confirms or flips it.", ""]
    for d in decisions:
        if d["status"] == "flipped":
            continue
        lines.append(f"- **{d['id']}** [{d['status']}] `{d['topic']}` — {d['text']} (by {d['by']}, {d['t'][:10]})")
    return "\n".join(lines) + "\n"


def cli(argv, cwd):
    """`twbuild decide …` — 사람이 읽는 출력은 한국어."""
    if not argv:
        root = main_root(cwd)
        led = ledger(root)
        if not led["decisions"]:
            return 0, "결정이 없다."
        return 0, "\n".join(f"{d['id']} [{d['status']}] {d['topic']} — {d['text']} ({d['by']})" for d in led["decisions"])
    if argv[0] == "confirm" and len(argv) == 2:
        d = confirm(cwd, argv[1])
        return 0, f"{d['id']} 확정."
    if argv[0] == "flip" and len(argv) >= 3:
        d = flip(cwd, argv[1], " ".join(argv[2:]))
        return 0, f"{d['flips']} 를 뒤집어 {d['id']} 로 확정: {d['text']}"
    by = "lead"
    if "--by" in argv:
        i = argv.index("--by")
        by = argv[i + 1] if i + 1 < len(argv) else ""
        argv = argv[:i] + argv[i + 2:]
    if len(argv) < 2:
        raise DecideError('decide <노드 ID> "<해석>" --by ios|android|lead')
    root, d, new = record(cwd, argv[0], " ".join(argv[1:]), by)
    if new:
        return 0, f"{d['id']} 기록(잠정): {d['topic']} — {d['text']}. 상대 플랫폼에는 훅이 주입한다."
    return 0, f"이미 있는 결정을 따른다 — {d['id']} [{d['status']}] {d['topic']} — {d['text']} (by {d['by']})"
