"""화면 순회(tour) — 레이아웃 트리 · 플랜에서 "한 번 실행으로 모든 화면을 돌며 찍는" UI 테스트를 생성하고 돌린다 (6장 기기 층).

환경은 골격이 깐다: iOS UI 테스트 타깃 + UITests/TwTour.swift, Android androidTest 의존성 + TwTour.kt (템플릿). 골격 이전 앱은 write() 가 채운다.
걷기 테스트(TwScreenTour)는 생성물이다 — 머지마다 머지된 화면으로 다시 쓰고(merge), 사이클 끝(done)에 두 플랫폼에서 한 번 돈다(설정 smoke.tour).

손잡이는 이미 있다: T1 이 트리의 모든 노드 ID 를 두 플랫폼 코드의 accessibilityIdentifier · testTag 로 강제하고, 각 화면 루트는 `n.<화면>` 이다.
경로는 결정적으로 뽑는다:
  - 핸들러 이름에 다른 화면 이름이 들어 있으면 그 화면으로 간다 (openSettings → settings, setTabSound → sound). close · hide · dismiss · reset · clear 로 시작하면 아니다
  - 플랜 interactions 에서 핸들러(또는 생성기가 붙인 Action 이름)와 `Route.<화면>` 이 한 줄에 있으면 그 화면으로 간다 (HOME-1: favPresetsOpen … → Route.nowPlaying)
  - 셸(host)이 슬롯으로 품은 화면에서는 셸의 핸들러(탭)도 누를 수 있다
  - skip 으로 시작하는 핸들러가 있는 화면은 첫 실행 관문(온보딩) — 새로 설치한 앱에서 먼저 찍고 건너뛴다 (실행기가 지우고 다시 깐다)
걷기: 깊이 우선 — 들어가 찍고, 그 화면에서 갈 곳을 다 돈 뒤 닫는 노드(close · hide · dismiss)나 셸의 부모 탭으로 돌아온다. 닫는 노드가 없으면 iOS 는 다시 띄워 되밟고 Android 는 시스템 뒤로.
생성물: apps/ios/UITests/TwScreenTour.swift · apps/android/app/src/androidTest/kotlin/<pkg>/TwScreenTour.kt.
"""
import json
import os
import re
import shutil
import subprocess
import time
from collections import deque

from . import config, draft, util

HEADER = "Generated by twbuild from the layout trees and plans — do not edit"
IOS_TEST = os.path.join("UITests", "TwScreenTour.swift")
NO_NAV = re.compile(r"^(close|hide|dismiss|reset|clear)", re.I)
ROUTE_RX = re.compile(r"Route\.(\w+)")


# ─────────────────────────── 경로 ───────────────────────────

def _handlers(lay):
    """[(노드 id 목록, 핸들러 식, Action 이름)] — on_click 만, 같은 식은 한 항목(노드는 트리 순서대로 모두 — 리스트가 비면 다음 후보)."""
    out, idx = [], {}

    def walk(n, scope):
        if not isinstance(n, dict):
            return
        if n.get("kind") == "list":
            scope = {**scope, n.get("as") or "item": draft._item_type(n["items"])}
        v = n.get("on_click")
        if isinstance(v, str) and n.get("id"):
            if v in idx:
                out[idx[v]][0].append(n["id"])
            else:
                head = v.split(".")[0]
                if head in scope:
                    it = scope[head]
                    action = draft.camel(it[:-4] if it.endswith("Item") else it) + draft.pascal(draft._flat(v[len(head) + 1:] or "tap"))
                else:
                    action = draft.camel(draft._flat(v))
                idx[v] = len(out)
                out.append(([n["id"]], v, action))
        for c in n.get("children") or []:
            walk(c, scope)
    walk(lay.get("root"), {})
    return out


def _close(lay):
    """화면을 닫는 노드 — close · hide · dismiss 핸들러 가운데 첫째. 루트 바로 밑의 자식 없는 box(시트 뒤 배경막)는 뒤로 미룬다: 가운데를 누르면 시트가 받는다."""
    root = lay.get("root") or {}
    backdrops = {c.get("id") for c in root.get("children") or [] if isinstance(c, dict) and c.get("kind") == "box" and not c.get("children")}
    found = [nid for ids, h, _ in _handlers(lay) if re.match(r"^(close|hide|dismiss)", h.split(".")[-1], re.I) for nid in ids]
    return next((n for n in found if n not in backdrops), found[0] if found else None)


def _slots(lay):
    out = []

    def walk(n):
        if isinstance(n, dict):
            if n.get("kind") == "screen" and n.get("ref"):
                out.append(n["ref"])
            for c in n.get("children") or []:
                walk(c)
    walk(lay.get("root"))
    return list(dict.fromkeys(out))


def _interactions(plan):
    it = (plan or {}).get("interactions") or []
    if isinstance(it, dict):
        return [f"{k}: {v}" for k, v in it.items()]
    return [str(x) for x in it]


def _built(root):
    """머지된 화면(원장 consumed) — 순회는 앱에 있는 화면만 돈다."""
    idx = util.read_json(os.path.join(root, util.DESIGN_DIR, "index.json"), {}) or {}
    return {k.split("/", 1)[1] for k, v in (idx.get("screens") or {}).items() if "/" in k and (v or {}).get("status") == "consumed"}


def _load(root, only=None):
    from . import yaml_lite
    lays, plans = {}, {}
    d = os.path.join(root, util.DESIGN_DIR)
    for feat in sorted(os.listdir(d)) if os.path.isdir(d) else []:
        ld = os.path.join(d, feat, "layout")
        if not os.path.isdir(ld):
            continue
        for n in sorted(os.listdir(ld)):
            if n.endswith(".json"):
                lay = util.read_json(os.path.join(ld, n), {}) or {}
                if lay.get("screen") and lay.get("root") and (only is None or lay["screen"] in only):
                    lays[lay["screen"]] = lay
                    plans[lay["screen"]] = yaml_lite.loads(util.read_text(os.path.join(root, util.TW_DIR, "plans", feat, f"{lay['screen']}.yaml"), "")) or {}
    return lays, plans


def plan_tour(root, only=None):
    """화면 이동 그래프 → 실행 화면에서 넓이 우선으로 뻗은 나무.
    → {"entry": {"screen", "skip"} | None, "start", "hosts": [셸], "reached": {화면: {"parent", "ids", "via", "host"}}, "order": [화면], "close": {화면: 노드}, "unreached": [화면]}
    host: 셸의 핸들러(탭)로 간 화면이면 그 셸 — 돌아올 때 셸의 다른 탭을 누른다."""
    lays, plans = _load(root, only)
    empty = {"entry": None, "start": None, "hosts": [], "reached": {}, "order": [], "close": {}, "unreached": []}
    if not lays:
        return empty
    screens = sorted(lays)
    hosts = {}
    for s, lay in lays.items():
        for ref in _slots(lay):
            if ref in lays:
                hosts.setdefault(ref, []).append(s)
    edges = {s: [] for s in screens}            # s → [(노드 id 목록, 핸들러, 목적 화면)]
    entry = None
    for s in screens:
        texts = _interactions(plans.get(s))
        for ids, h, action in _handlers(lays[s]):
            name = h.split(".")[-1]
            if name.lower().startswith("skip") and entry is None:
                entry = {"screen": s, "skip": ids[0]}
                continue
            targets = []
            if not NO_NAV.match(name):
                targets += [t for t in screens if t != s and draft.pascal(t) in h]
            for line in texts:
                if action in line or (("." not in h) and re.search(rf"\b{re.escape(h)}\b", line)):
                    targets += [t for r in ROUTE_RX.findall(line) for t in screens if t.lower() == r.lower() and t != s]
            for t in dict.fromkeys(targets):
                edges[s].append((ids, h, t))
    shells = [s for s in screens if _slots(lays[s])]
    host = next((s for s in shells if lays[s].get("kind") == "shell"), shells[0] if shells else None)
    start = (_slots(lays[host])[0] if host else None) or next((s for s in screens if s != (entry or {}).get("screen")), screens[0])
    reached = {start: {"parent": None, "ids": [], "via": None, "host": None}}
    if host:
        reached[host] = {"parent": None, "ids": [], "via": None, "host": None}      # 셸은 첫 슬롯 화면을 보인 채로 뜬다 — 따로 찍지 않는다
    q = deque([start])
    while q:
        s = q.popleft()
        own = [(ids, h, t, None) for ids, h, t in edges.get(s, [])]
        via_host = [(ids, h, t, hs) for hs in hosts.get(s, []) for ids, h, t in edges.get(hs, [])]
        for ids, h, t, hs in own + via_host:
            if t not in reached and t != (entry or {}).get("screen"):
                reached[t] = {"parent": s, "ids": ids, "via": h, "host": hs}
                q.append(t)
    order = [s for s in reached if s not in ([host] if host else [])]
    unreached = [s for s in screens if s not in reached and s != (entry or {}).get("screen")]
    return {"entry": entry, "start": start, "hosts": [host] if host else [], "reached": reached, "order": order,
            "close": {s: _close(lays[s]) for s in screens}, "edges": edges, "unreached": unreached}


def _path_to(reached, s):
    """실행 화면에서 s 까지 누를 것 — [(노드 목록, 핸들러)]."""
    out = []
    while s and reached[s]["parent"]:
        out.insert(0, (reached[s]["ids"], reached[s]["via"]))
        s = reached[s]["parent"]
    return out


def focus(t, screen):
    """한 화면만 — 그 화면까지 곧장 가서 찍는다 (스모크의 시각 층). 못 가는 화면이면 None."""
    if not t.get("start"):
        return None
    e = t.get("entry")
    if e and e["screen"] == screen:
        return [("shot", screen)]
    if screen not in t["reached"] or screen in t.get("hosts", []):
        return None
    ops = [("expect", e["screen"]), ("tap", [e["skip"]], "first-run gate: " + e["screen"]), ("gone", e["screen"])] if e else []
    ops.append(("expect", t["start"]))
    ops += [("tap", ids, via) for ids, via in _path_to(t["reached"], screen)]
    ops.append(("shot", screen))
    return ops


def walk(t):
    """한 번 실행으로 도는 순서 — [("shot", 화면) | ("tap", [노드], 핸들러) | ("gone", 화면) | ("expect", 화면) | ("back", 화면, [(노드 목록, 핸들러)])].
    깊이 우선: 들어가 찍고, 그 화면에서 갈 곳을 다 돈 뒤 닫고 나온다. 자기 핸들러로 연 화면은 닫는 노드로, 셸 탭으로 연 화면은 셸의 부모 탭으로 돌아온다.
    닫는 노드가 없으면 back — iOS 는 다시 띄워 경로를 되밟고, Android 는 시스템 뒤로."""
    if not t.get("start"):
        return []
    reached = t["reached"]
    kids = {}
    for s in t["order"]:
        p = reached[s]["parent"]
        if p:
            kids.setdefault(p, []).append(s)

    def path_to(s):
        return _path_to(reached, s)

    ops = []
    if t.get("entry"):
        e = t["entry"]
        ops += [("shot", e["screen"]), ("tap", [e["skip"]], "first-run gate: " + e["screen"]), ("gone", e["screen"])]
    ops.append(("shot", t["start"]))

    def dfs(s):
        for c in sorted(kids.get(s, []), key=lambda c: reached[c]["host"] is not None):     # 자기 이동 먼저, 탭은 나중
            r = reached[c]
            ops.append(("tap", r["ids"], r["via"]))
            ops.append(("shot", c))
            dfs(c)
            if r["host"]:
                back = next(((ids, h) for ids, h, tt in t["edges"].get(r["host"], []) if tt == s), None)
                ops.extend([("tap", back[0], back[1]), ("expect", s)] if back else [("back", s, path_to(s)), ("expect", s)])
            elif t["close"].get(c):
                ops.extend([("tap", [t["close"][c]], "close " + c), ("gone", c), ("expect", s)])
            else:
                ops.extend([("back", s, path_to(s)), ("expect", s)])
    dfs(t["start"])
    while ops and ops[-1][0] != "shot":                 # 마지막 화면을 찍은 뒤 되돌아가는 단계는 필요 없다
        ops.pop()
    return ops


# ─────────────────────────── 생성 ───────────────────────────

def _q(s):
    return json.dumps(s, ensure_ascii=False)


def _ids(ids):
    return ", ".join(_q(i) for i in ids)


def _comment(t):
    L = [f"Screen tour — one launch walks every built screen reachable from the launch screen and captures it."]
    if t.get("unreached"):
        L.append("Not reached (no navigation in the trees · plans): " + ", ".join(t["unreached"]))
    return L


def swift(t, vars_, ops=None, cls="TwScreenTour"):
    L = [f"// {HEADER}"] + [f"// {c}" for c in _comment(t)] + ["import XCTest", "",
         "@MainActor", f"final class {cls}: XCTestCase {{",
         "    override func setUp() { continueAfterFailure = false }", "",
         "    func test_tour() {",
         "        let t = TwTour(self)",
         "        t.launch()"]
    for op in walk(t) if ops is None else ops:
        k = op[0]
        if k == "shot":
            L.append(f"        t.shot({_q(op[1])})")
        elif k == "tap":
            L.append(f"        t.tap([{_ids(op[1])}], {_q(op[2])})")
        elif k == "gone":
            L.append(f"        t.gone({_q(op[1])})")
        elif k == "expect":
            L.append(f"        t.expect({_q(op[1])})")
        elif k == "back":                                # 닫는 노드가 없다 — 다시 띄워 그 화면까지 되밟는다
            L.append(f"        t.relaunch()  // no close control: back to {op[1]} by replaying the path")
            L += [f"        t.tap([{_ids(ids)}], {_q(h)})" for ids, h in op[2]]
    L += ["    }", "}", ""]
    return "\n".join(L)


def kotlin(t, vars_, ops=None, cls="TwScreenTour"):
    L = [f"// {HEADER}"] + [f"// {c}" for c in _comment(t)] + [f"package {vars_['id']}", "",
         "import androidx.compose.ui.test.junit4.createAndroidComposeRule",
         "import androidx.test.ext.junit.runners.AndroidJUnit4",
         "import org.junit.Rule",
         "import org.junit.Test",
         "import org.junit.runner.RunWith", "",
         "@RunWith(AndroidJUnit4::class)",
         f"class {cls} {{",
         "    @get:Rule val rule = createAndroidComposeRule<MainActivity>()", "",
         "    @Test fun tour() {",
         "        val t = TwTour(rule)"]
    for op in walk(t) if ops is None else ops:
        k = op[0]
        if k == "shot":
            L.append(f"        t.shot({_q(op[1])})")
        elif k == "tap":
            L.append(f"        t.tap(listOf({_ids(op[1])}), {_q(op[2])})")
        elif k == "gone":
            L.append(f"        t.gone({_q(op[1])})")
        elif k == "expect":
            L.append(f"        t.expect({_q(op[1])})")
        elif k == "back":
            L.append(f"        t.back()  // no close control: system back to {op[1]}")
    L += ["    }", "}", ""]
    return "\n".join(L)


def android_test_rel(vars_, name="TwScreenTour.kt"):
    return os.path.join("apps", "android", "app", "src", "androidTest", "kotlin", vars_["pkg_path"], name)


SUPPORT = {"ios": (os.path.join("monorepo", "ios", "UITests", "TwTour.swift"), lambda v: os.path.join("apps", "ios", "UITests", "TwTour.swift")),
           "android": (os.path.join("monorepo", "android", "app", "src", "androidTest", "kotlin", "__pkg__", "TwTour.kt"), lambda v: android_test_rel(v, "TwTour.kt"))}


def expected(root, cfg=None):
    """생성물(걷기 테스트) — 머지된 화면만. 지원 파일(TwTour)은 골격 소유라 여기 없다."""
    cfg = cfg or config.load(root)
    vars_ = config.app_vars(cfg)
    t = plan_tour(root, _built(root))
    if not t["start"]:
        return {}
    out = {}
    plats = cfg.get("platforms") or []
    if "ios" in plats:
        out[os.path.join("apps", "ios", IOS_TEST)] = swift(t, vars_)
    if "android" in plats:
        out[android_test_rel(vars_)] = kotlin(t, vars_)
    return out


IOS_TARGET_MARK = "# twbuild: screen tour UI tests"
ANDROID_MARK = "// twbuild: screen tour (androidTest)"


def _wire_ios(root, product):
    """project.yml 에 UI 테스트 타깃 · 스킴 테스트 등록 — 골격(템플릿)엔 처음부터 있다. 그 전에 만든 앱만 고친다 (멱등, 사람 줄은 그대로)."""
    p = os.path.join(root, "apps", "ios", "project.yml")
    text = util.read_text(p, None)
    if text is None or IOS_TARGET_MARK in text or re.search(rf"^  {re.escape(product)}UITests:", text, re.M):
        return False
    lines = text.split("\n")
    try:
        ti = next(i for i, l in enumerate(lines) if l.rstrip() == "targets:")
    except StopIteration:
        return False
    end = next((i for i in range(ti + 1, len(lines)) if lines[i] and not lines[i].startswith((" ", "#"))), len(lines))
    while end > ti + 1 and not lines[end - 1].strip():
        end -= 1
    block = [f"  {IOS_TARGET_MARK}", f"  {product}UITests:", "    type: bundle.ui-testing", "    platform: iOS", "    sources:", "      - path: UITests",
             "    dependencies:", f"      - target: {product}", "    settings:", "      base:",
             f"        PRODUCT_BUNDLE_IDENTIFIER: {config.app_vars(config.load(root))['id']}.uitests", "        GENERATE_INFOPLIST_FILE: YES",
             f"        TEST_TARGET_NAME: {product}"]
    lines[end:end] = block
    try:
        ai = next(i for i, l in enumerate(lines) if l.rstrip() == f"  {product}:")
        if not any("testTargets" in l for l in lines[ai:ai + 4]):
            lines[ai + 1:ai + 1] = ["    scheme:", f"      testTargets: [{product}UITests]"]
    except StopIteration:
        pass
    util.write_text(p, "\n".join(lines))
    return True


def _wire_android(root):
    """app/build.gradle.kts — instrumentation runner · androidTest 의존성. 골격엔 처음부터 있다 — 그 전에 만든 앱만 고친다 (멱등)."""
    p = os.path.join(root, "apps", "android", "app", "build.gradle.kts")
    text = util.read_text(p, None)
    if text is None or ANDROID_MARK in text or "ui-test-junit4" in text:
        return False
    if "testInstrumentationRunner" not in text:
        text = text.replace("    defaultConfig {\n", "    defaultConfig {\n        testInstrumentationRunner = \"androidx.test.runner.AndroidJUnitRunner\"\n", 1)
    m = re.search(r"\ndependencies\s*\{", text)
    if not m:
        return False
    close = text.find("\n}", m.end())
    add = (f"\n    {ANDROID_MARK}\n"
           "    androidTestImplementation(platform(libs.androidx.compose.bom))\n"
           "    androidTestImplementation(\"androidx.compose.ui:ui-test-junit4\")\n"
           "    androidTestImplementation(\"androidx.test.ext:junit:1.2.1\")\n"
           "    androidTestImplementation(\"androidx.test:runner:1.6.2\")")
    text = text[:close] + add + text[close:]
    util.write_text(p, text)
    return True


def write(root, cfg=None):
    """걷기 테스트를 다시 쓰고, 골격 이전에 만든 앱이면 지원 파일 · 프로젝트 배선을 채운다. → 바뀐 파일(상대 경로)."""
    cfg = cfg or config.load(root)
    vars_ = config.app_vars(cfg)
    files = expected(root, cfg)
    changed = []
    for rel, text in files.items():
        if util.read_text(os.path.join(root, rel), None) != text:
            util.write_text(os.path.join(root, rel), text)
            changed.append(rel)
    plats = {p for p in ("ios", "android") if any(r.startswith(os.path.join("apps", p)) for r in files)}
    for p in sorted(plats):
        src, dest = SUPPORT[p]
        rel = dest(vars_)
        if not os.path.isfile(os.path.join(root, rel)):
            util.write_text(os.path.join(root, rel), util.render(util.read_text(os.path.join(util.TEMPLATES, src)), vars_))
            changed.append(rel)
    if "ios" in plats and _wire_ios(root, vars_["product"]):
        changed.append(os.path.join("apps", "ios", "project.yml"))
    if "android" in plats and _wire_android(root):
        changed.append(os.path.join("apps", "android", "app", "build.gradle.kts"))
    return sorted(changed)


def drift(root, cfg=None):
    return [rel for rel, text in expected(root, cfg).items() if util.read_text(os.path.join(root, rel), None) != text]


