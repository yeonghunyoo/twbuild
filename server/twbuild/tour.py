def _sh(cmd, cwd=None, timeout=600, log=None, env=None):
    try:
        r = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True, timeout=timeout, env=env)
        out = (r.stdout or "") + (r.stderr or "")
    except subprocess.TimeoutExpired:
        return 124, f"시간 초과 {timeout}s: {' '.join(cmd[:3])}"
    except OSError as e:
        return 127, str(e)
    if log is not None:
        log.append(f"$ {' '.join(cmd)}\n{out[-4000:]}")
    return r.returncode, out


def _ios_udid():
    rc, out = _sh(["xcrun", "simctl", "list", "-j", "devices"], timeout=30)
    if rc != 0:
        return None
    devs = [d for rt, ds in (json.loads(out).get("devices") or {}).items() if "iOS" in rt for d in ds if d.get("isAvailable")]
    booted = [d for d in devs if d.get("state") == "Booted" and "iPhone" in d.get("name", "")]
    return (booted or [d for d in devs if "iPhone" in d.get("name", "")] or [None])[0]


def run_ios(base, vars_, out_dir, timeout=1500, cls="TwScreenTour"):
    """xcodebuild test 로 순회 → 첨부 스크린샷을 out_dir/<화면>-ios.png 로. → {"status", "detail", "screens": {화면: png}, "failures": [..], "log"}"""
    log = []
    t0 = time.time()
    dev = _ios_udid()
    if not dev or not shutil.which("xcodebuild"):
        return {"status": "unmeasured", "detail": "시뮬레이터 · Xcode 없음", "screens": {}, "failures": [], "log": ""}
    udid = dev["udid"]
    if dev.get("state") != "Booted":
        _sh(["xcrun", "simctl", "bootstatus", udid, "-b"], timeout=240, log=log)
    # 첫 실행 관문(온보딩)을 찍으려면 새로 설치 — 지우기만 하면 시뮬레이터의 cfprefsd 가 UserDefaults 를 붙들고 있다가 새 설치에 돌려준다 (실측)
    _sh(["xcrun", "simctl", "terminate", udid, vars_["id"]], timeout=30, log=log)
    _sh(["xcrun", "simctl", "spawn", udid, "defaults", "delete", vars_["id"]], timeout=30, log=log)
    _sh(["xcrun", "simctl", "uninstall", udid, vars_["id"]], timeout=60, log=log)
    app = os.path.join(base, "apps", "ios")
    _sh(["xcodegen", "generate", "--quiet"], cwd=app, timeout=120, log=log)
    rb = os.path.join(out_dir, "tour-ios.xcresult")
    shutil.rmtree(rb, ignore_errors=True)
    os.makedirs(out_dir, exist_ok=True)
    rc, out = _sh(["xcodebuild", "test", "-project", f"{vars_['product']}.xcodeproj", "-scheme", vars_["product"],
                   "-destination", f"platform=iOS Simulator,id={udid}", "-derivedDataPath", os.path.join(base, ".twbuild", "derived", "ios-tour"),
                   "-resultBundlePath", rb, "-only-testing", f"{vars_['product']}UITests/{cls}", "CODE_SIGNING_ALLOWED=NO"],
                  cwd=app, timeout=timeout, log=log)
    failures = sorted(set(re.findall(r"tour: ([^\n\"]+)", out)))
    screens = {}
    if os.path.isdir(rb):
        ex = os.path.join(out_dir, "tour-ios-attachments")
        shutil.rmtree(ex, ignore_errors=True)
        _sh(["xcrun", "xcresulttool", "export", "attachments", "--path", rb, "--output-path", ex], timeout=120, log=log)
        man = util.read_json(os.path.join(ex, "manifest.json"), []) or []
        for test in man:
            for a in test.get("attachments") or []:
                m = re.match(r"tw-((?:fail-)?[A-Za-z0-9]+)_", a.get("suggestedHumanReadableName") or "")
                if m and a.get("exportedFileName"):
                    dest = os.path.join(out_dir, f"{m.group(1)}-ios.png")
                    shutil.copyfile(os.path.join(ex, a["exportedFileName"]), dest)
                    screens[m.group(1)] = dest
        shutil.rmtree(ex, ignore_errors=True)
    return _result(screens, failures, rc == 0, t0, log, "" if rc == 0 else f"xcodebuild exit {rc}")


def run_android(base, vars_, out_dir, tools=None, timeout=1500, cls="TwScreenTour"):
    """gradle 로 앱 · 테스트 APK 설치 → am instrument → run-as 로 PNG 를 꺼낸다. → run_ios 와 같은 모양"""
    from . import probe
    log = []
    t0 = time.time()
    tools = tools or probe.toolchain()
    adb = tools.get("adb")
    app = os.path.join(base, "apps", "android")
    gradlew = os.path.join(app, "gradlew")
    if not adb or not os.path.isfile(gradlew):
        return {"status": "unmeasured", "detail": "adb · gradlew 없음", "screens": {}, "failures": [], "log": ""}
    rc, out = _sh([adb, "devices"], timeout=20)
    serials = [l.split()[0] for l in out.splitlines()[1:] if l.strip().endswith("device")]
    if not serials:
        return {"status": "unmeasured", "detail": "연결된 기기 · 에뮬레이터가 없다", "screens": {}, "failures": [], "log": ""}
    serial, pkg = serials[0], vars_["id"]
    env = {**os.environ, "ANDROID_SERIAL": serial, "ANDROID_HOME": tools.get("android_sdk") or os.environ.get("ANDROID_HOME", "")}
    _sh([adb, "-s", serial, "uninstall", pkg], timeout=60, log=log)
    rc, out = _sh([gradlew, "installDebug", "installDebugAndroidTest", "-q"], cwd=app, timeout=timeout, log=log, env=env)
    if rc != 0:
        return {"status": "fail", "detail": f"테스트 APK 빌드 · 설치 실패 (exit {rc})", "screens": {}, "failures": [next((l.strip() for l in out.splitlines() if l.startswith("e: ")), out.strip().splitlines()[-1] if out.strip() else "")[:300]], "log": "\n".join(log)[-6000:]}
    rc, out = _sh([adb, "-s", serial, "shell", "am", "instrument", "-w", "-e", "class", f"{pkg}.{cls}", f"{pkg}.test/androidx.test.runner.AndroidJUnitRunner"],
                  timeout=timeout, log=log)
    failures = sorted(set(re.findall(r"tour: ([^\n]+)", out)))
    screens = {}
    os.makedirs(out_dir, exist_ok=True)
    rc2, listing = _sh([adb, "-s", serial, "shell", "run-as", pkg, "ls", "files/twbuild-tour"], timeout=30)
    for name in listing.split():
        if name.endswith(".png"):
            dest = os.path.join(out_dir, f"{name[:-4]}-android.png")
            try:
                r = subprocess.run([adb, "-s", serial, "exec-out", "run-as", pkg, "cat", f"files/twbuild-tour/{name}"], capture_output=True, timeout=60)
                if r.returncode == 0 and r.stdout[:4] == b"\x89PNG":
                    with open(dest, "wb") as f:
                        f.write(r.stdout)
                    screens[name[:-4]] = dest
            except (OSError, subprocess.SubprocessError):
                pass
    ok = "FAILURES!!!" not in out and "OK (" in out
    return _result(screens, failures or (["instrumentation: " + out.strip().splitlines()[-1]] if not ok and out.strip() else []), ok, t0, log, "")


def _result(shots, failures, ok, t0, log, extra):
    """→ {"status", "detail", "screens": {화면: png}, "fail_shot": png?, "failures", "log"} — 실패한 자리의 화면은 tw-fail-<화면> 으로 따로 온다."""
    screens = {k: v for k, v in shots.items() if not k.startswith("fail-")}
    fail_shot = next((v for k, v in sorted(shots.items()) if k.startswith("fail-")), None)
    status = "pass" if ok and screens else ("fail" if screens or failures or fail_shot else "unmeasured")
    detail = f"화면 {len(screens)}개 캡처 · {round(time.time() - t0)}s" + (f" · 실패: {'; '.join(failures)}" if failures else "") + (f" · {extra}" if extra else "")
    out = {"status": status, "detail": detail, "screens": screens, "failures": failures, "log": "\n".join(log)[-6000:]}
    if fail_shot:
        out["fail_shot"] = fail_shot
    return out


def run(base, platform, vars_, out_dir, tools=None, cls="TwScreenTour"):
    if os.environ.get("TWBUILD_NO_BUILD"):
        return {"status": "unmeasured", "detail": "TWBUILD_NO_BUILD", "screens": {}, "failures": [], "log": ""}
    try:
        return run_ios(base, vars_, out_dir, cls=cls) if platform == "ios" else run_android(base, vars_, out_dir, tools, cls=cls)
    except Exception as e:                                        # noqa: BLE001 — 순회가 하네스를 죽이면 안 된다
        return {"status": "unmeasured", "detail": f"내부 오류: {type(e).__name__}: {e}", "screens": {}, "failures": [], "log": ""}


FOCUS = "TwFocusTour"


def focus_files(root, wt_vars, screen, cfg):
    """시각 층의 한 화면 순회 — {상대 경로: 본문}. 트리 · 플랜은 메인 레포, 화면은 머지된 것 + 이 화면. 못 가면 {}."""
    t = plan_tour(root, _built(root) | {screen})
    ops = focus(t, screen)
    if not ops:
        return {}
    plats = cfg.get("platforms") or []
    out = {}
    if "ios" in plats:
        out[os.path.join("apps", "ios", "UITests", f"{FOCUS}.swift")] = swift(t, wt_vars, ops, FOCUS)
    if "android" in plats:
        out[android_test_rel(wt_vars, f"{FOCUS}.kt")] = kotlin(t, wt_vars, ops, FOCUS)
    return out


def run_focus(root, wt, platform, vars_, screen, out_dir, cfg=None, tools=None):
    """워크트리에서 그 화면까지만 돌아 찍는다 — 테스트 파일은 잠깐 두었다 지운다(개발자 브랜치에 남기지 않는다).
    → run() 과 같은 모양 + "shot": 그 화면 PNG | None"""
    cfg = cfg or config.load(root)
    files = {rel: text for rel, text in focus_files(root, vars_, screen, cfg).items() if rel.startswith(os.path.join("apps", platform))}
    if not files:
        return {"status": "unmeasured", "detail": f"{screen}: 순회로 갈 수 없는 화면 (트리 · 플랜에 이동이 없다)", "screens": {}, "failures": [], "log": "", "shot": None}
    for rel, text in files.items():
        util.write_text(os.path.join(wt, rel), text)
    try:
        r = run(wt, platform, vars_, out_dir, tools, cls=FOCUS)
    finally:
        for rel in files:
            try:
                os.remove(os.path.join(wt, rel))
            except OSError:
                pass
    r["shot"] = r["screens"].get(screen)
    return r


def cli(argv, root):
    """`twbuild tour [plan|write|ios|android]` — 경로 보기 · 생성 · 실행(메인 레포, 결과는 .twbuild/reports/tour/)."""
    cfg = config.load(root)
    sub = argv[0] if argv else "plan"
    if sub == "plan":
        built = _built(root)
        t = plan_tour(root, built if "--all" not in argv else None)
        if not t["start"]:
            return 0, "머지된 화면이 없다 (--all: 트리 전부)"
        lines = []
        for op in walk(t):
            if op[0] == "shot":
                lines.append(f"📸 {op[1]}")
            elif op[0] == "tap":
                lines.append(f"   탭 {op[2]}  [{op[1][0]}{' …' if len(op[1]) > 1 else ''}]")
            elif op[0] == "back":
                lines.append(f"   뒤로 → {op[1]}")
        if t["hosts"]:
            lines.append(f"셸 {', '.join(t['hosts'])} 은 슬롯 화면과 같이 찍힌다")
        if t["unreached"]:
            lines.append("못 가는 화면(트리 · 플랜에 이동이 없다): " + ", ".join(t["unreached"]))
        return 0, "\n".join(lines)
    if sub == "write":
        return 0, "생성: " + ", ".join(write(root, cfg))
    if sub in ("ios", "android"):
        write(root, cfg)
        out = run(root, sub, config.app_vars(cfg), util.tw(root, "reports", "tour"))
        lines = [f"{sub} 순회 {out['status']} — {out['detail']}"] + [f"  {k}: {os.path.relpath(v, root)}" for k, v in sorted(out["screens"].items())]
        if out.get("fail_shot"):
            lines.append(f"  실패한 자리: {os.path.relpath(out['fail_shot'], root)}")
        return (0 if out["status"] == "pass" else 1), "\n".join(lines)
    return 2, "twbuild tour [plan|write|ios|android]"
