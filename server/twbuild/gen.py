def _success(doc, op):
    """2xx 응답 중 가장 낮은 상태 → (status, schema|None). 없으면 (None, None)."""
    for status in sorted((op.get("responses") or {}), key=lambda s: (not str(s).isdigit(), int(s) if str(s).isdigit() else 0)):
        if not str(status).startswith("2"):
            continue
        resp = _resolve(doc, (op["responses"] or {})[status], "responses")
        media = (resp.get("content") or {}).get("application/json") or {}
        return status, media.get("schema")
    return None, None


def operations(doc, types):
    """[{name, method, path, summary, secured, path_params, query, headers, body, body_required, returns}] — 라우트 순서(contract.routes)."""
    out = []
    doc_sec = doc.get("security") or []
    for r in contract.routes(doc):
        op = (doc["paths"][r["path"]] or {}).get(r["method"].lower()) or {}
        path_item = doc["paths"][r["path"]] or {}
        params = [_resolve(doc, p, "parameters") for p in (path_item.get("parameters") or []) + (op.get("parameters") or [])]
        name = camel(r["name"])
        pp, qq, hh = [], [], []
        for p in params:
            entry = {"name": camel(p.get("name")), "json": p.get("name"),
                     "type": types.ref(p.get("schema") or {"type": "string"}, pascal(name) + pascal(p.get("name")), inline_ok=False),
                     "required": bool(p.get("required")) or p.get("in") == "path"}
            {"path": pp, "query": qq, "header": hh}.get(p.get("in"), []).append(entry)
        body_t, body_req = None, False
        rb = op.get("requestBody")
        if rb:
            rb = _resolve(doc, rb, "requestBodies")
            media = (rb.get("content") or {}).get("application/json") or {}
            if media.get("schema") is not None:
                body_t, body_req = types.ref(media["schema"], pascal(name) + "Body"), bool(rb.get("required"))
        status, rs = _success(doc, op)
        returns = types.ref(rs, pascal(name) + "Response") if rs is not None else None
        sec = op.get("security") if "security" in op else doc_sec
        out.append({"name": name, "method": r["method"], "path": r["path"], "summary": r["summary"], "secured": bool(sec),
                    "path_params": pp, "query": qq, "headers": hh, "body": body_t, "body_required": body_req, "returns": returns, "status": status})
    return out


