def _swift_models(types):
    L = [f"// {HEADER}", "import Foundation", ""]
    if types.uses_any:
        L += [_JSON_VALUE_SWIFT, ""]
    for name in sorted(types.types):
        t = types.types[name]
        if t["kind"] == "enum":
            L.append(f"public enum {name}: String, Codable, Equatable, Sendable {{")
            for v in t["values"]:
                L.append(f"    case {_sw(camel(v))} = {_str_lit(v)}")
            L += ["}", ""]
        elif t["kind"] == "alias":
            L += [f"public typealias {name} = {_swift_type(t['type'])}", ""]
        else:
            if t.get("doc"):
                L.append(f"/// {t['doc']}")
            L.append(f"public struct {name}: Codable, Equatable, Sendable {{")
            for f in t["fields"]:
                if f.get("doc"):
                    L.append(f"    /// {f['doc']}")
                L.append(f"    public let {_sw(f['name'])}: {_swift_type(f['type'])}{'?' if f['optional'] else ''}")
            args = ", ".join(f"{_sw(f['name'])}: {_swift_type(f['type'])}{'? = nil' if f['optional'] else ''}" for f in t["fields"])
            L += ["", f"    public init({args}) {{"]
            for f in t["fields"]:
                L.append(f"        self.{_sw(f['name'])} = {_sw(f['name'])}")
            L.append("    }")
            if any(f["name"] != f["json"] for f in t["fields"]):
                L += ["", "    private enum CodingKeys: String, CodingKey {"]
                for f in t["fields"]:
                    L.append(f"        case {_sw(f['name'])} = {_str_lit(f['json'])}")
                L.append("    }")
            L += ["}", ""]
    return "\n".join(L).rstrip("\n") + "\n"


def _swift_param_str(p):
    """경로 · 쿼리 값 → 문자열 식."""
    expr = _sw(p["name"])
    if p["type"] == ("prim", "string"):
        return expr
    return f"String(describing: {expr})"


