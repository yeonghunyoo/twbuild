_INIT_GRADLE = """// twbuild — contract decoding layer needs JUnit 4 on the unit-test classpath; added here so the app's build files stay untouched.
allprojects {
    afterEvaluate {
        if (plugins.hasPlugin("com.android.application") || plugins.hasPlugin("com.android.library")) {
            dependencies { add("testImplementation", "junit:junit:4.13.2") }
        }
    }
}
"""


def _run(cmd, cwd, lf, timeout, env=None):
    lf.write(f"$ {' '.join(cmd)}\n")
    lf.flush()
    try:
        r = subprocess.run(cmd, cwd=cwd, stdout=lf, stderr=subprocess.STDOUT, text=True, timeout=timeout, env=env or os.environ)
        return r.returncode
    except subprocess.TimeoutExpired:
        lf.write(f"timeout {timeout}s\n")
        return None


def decode_check(root, platform, log_path, timeout=900, cfg=None):
    """계약의 응답 예시 전부를 생성 모델로 디코딩한다 → {"status": pass|fail|unmeasured, "detail", "log"}.

    iOS: Models.swift + 임시 main.swift 를 swiftc 로 묶어 실행. Android: 생성 JUnit 테스트(ContractDecodeTest)를 gradlew 로 실행.
    툴체인 · gradlew 가 없거나 TWBUILD_NO_BUILD 면 unmeasured — 통과로 세지 않는다.
    """
    from . import probe
    if os.environ.get("TWBUILD_NO_BUILD"):
        return {"status": "unmeasured", "detail": "TWBUILD_NO_BUILD", "log": ""}
    try:
        cfg = cfg or config.load(root)                  # 워크트리에는 config 가 없다 — smoke 가 메인 레포 설정을 넘긴다
        doc = contract.merged(root)
    except (contract.ContractError, GenError) as e:
        return {"status": "fail", "detail": f"계약 오류: {e}", "log": ""}
    types = _Types(doc)
    exs = examples(doc, types, operations(doc, types))      # 인라인 타입까지 모델에 들어가도록 오퍼레이션을 먼저 훑는다
    skipped = _responses_without_example(doc)
    if not exs:
        return {"status": "unmeasured", "detail": "계약에 응답 예시가 없다", "log": ""}
    os.makedirs(os.path.dirname(log_path) or ".", exist_ok=True)
    note = f"예시 {len(exs)}개" + (f" · 예시 없는 응답 {skipped}개" if skipped else "")
    t = probe.toolchain()
    if platform == "ios":
        if not shutil.which("xcrun") or not t["xcodebuild"]:
            return {"status": "unmeasured", "detail": "Xcode(swiftc) 없음", "log": ""}
        work = util.tw(root, "decode", "ios")
        shutil.rmtree(work, ignore_errors=True)
        os.makedirs(work, exist_ok=True)
        util.write_text(os.path.join(work, "Models.swift"), _swift_models(types))
        util.write_text(os.path.join(work, "main.swift"), _swift_decode_main(exs))
        with open(log_path, "w", encoding="utf-8") as lf:
            code = _run(["xcrun", "swiftc", "-swift-version", "5", "-o", "decode", "main.swift", "Models.swift"], work, lf, timeout)
            if code is None:
                return {"status": "unmeasured", "detail": f"swiftc 시간 초과 {timeout}s", "log": log_path}
            if code != 0:
                return {"status": "fail", "detail": f"Models.swift 컴파일 실패 (exit {code}) · {note}", "log": log_path}
            code = _run([os.path.join(work, "decode")], work, lf, timeout)
        if code is None:
            return {"status": "unmeasured", "detail": f"디코딩 실행 시간 초과 {timeout}s", "log": log_path}
        if code != 0:
            fails = [l[5:] for l in util.read_text(log_path).splitlines() if l.startswith("FAIL ")]
            return {"status": "fail", "detail": f"디코딩 실패 {len(fails)}개: " + "; ".join(f.split(":")[0] for f in fails[:5]) + f" · {note}", "log": log_path}
        return {"status": "pass", "detail": f"{note} 모두 디코딩", "log": log_path}
    # android
    if not t["android_sdk"] or not t["java"]:
        return {"status": "unmeasured", "detail": "Android SDK · JDK 없음", "log": ""}
    app = util.app_dir(root, "android")
    gradlew = os.path.join(app, "gradlew")
    if not os.path.isfile(gradlew):
        return {"status": "unmeasured", "detail": "gradlew 없음 — 셋업 selfcheck 가 만든다", "log": ""}
    pkg = config.app_vars(cfg)["id"]
    test_rel = _paths(cfg)["android_test"]
    util.write_text(os.path.join(root, test_rel), _kt_decode_test(exs, pkg))
    init = util.tw(root, "decode", "junit.init.gradle.kts")
    util.write_text(init, _INIT_GRADLE)
    sdk_props = os.path.join(app, "local.properties")
    if not os.path.isfile(sdk_props):
        util.write_text(sdk_props, f"sdk.dir={t['android_sdk']}\n")
    fqcn = f"{pkg}.core.networking.generated.ContractDecodeTest"
    with open(log_path, "w", encoding="utf-8") as lf:
        code = _run([gradlew, "-I", init, "testDebugUnitTest", "--tests", fqcn, "-q"], app, lf, timeout,
                    env={**os.environ, "ANDROID_HOME": t["android_sdk"] or os.environ.get("ANDROID_HOME", "")})
    if code is None:
        return {"status": "unmeasured", "detail": f"gradlew 시간 초과 {timeout}s", "log": log_path}
    if code != 0:
        xml = util.read_text(os.path.join(app, "app", "build", "test-results", "testDebugUnitTest", f"TEST-{fqcn}.xml"), "")
        failed = [exs[int(i)]["name"] for i in re.findall(r'<testcase name="decode(\d+)"[^>]*>\s*<failure', xml) if int(i) < len(exs)]
        detail = (f"디코딩 실패 {len(failed)}개: " + "; ".join(failed[:5])) if failed else f"테스트 실행 실패 (exit {code})"
        return {"status": "fail", "detail": f"{detail} · {note}", "log": log_path}
    return {"status": "pass", "detail": f"{note} 모두 디코딩", "log": log_path}
