# TypeRef: ("prim", "string"|"int"|"int64"|"double"|"bool") · ("ref", Name) · ("array", T) · ("map", T) · ("any",)
# 타입: {"kind": "struct", "name", "fields": [{"name", "json", "type", "optional", "doc"}], "doc"}
#       {"kind": "enum", "name", "values": [str]}  ·  {"kind": "alias", "name", "type"}

def _ref_name(ref):
    m = re.match(r"^#/components/schemas/([^/]+)$", ref or "")
    if not m:
        raise GenError(f"지원하지 않는 $ref: {ref}")
    return type_name(m.group(1))


def _resolve(doc, node, kind="schemas"):
    """$ref 를 따라간다 (schemas · responses · parameters · requestBodies)."""
    seen = 0
    while isinstance(node, dict) and "$ref" in node:
        ref = node["$ref"]
        m = re.match(r"^#/components/([^/]+)/([^/]+)$", ref)
        if not m:
            raise GenError(f"지원하지 않는 $ref: {ref}")
        node = ((doc.get("components") or {}).get(m.group(1)) or {}).get(m.group(2))
        if node is None:
            raise GenError(f"없는 참조: {ref}")
        seen += 1
        if seen > 20:
            raise GenError(f"$ref 순환: {ref}")
    return node or {}


class _Types:
    """컴포넌트 스키마와 인라인 스키마를 이름 있는 타입으로 모은다. 순서는 이름순(결정적)."""

    def __init__(self, doc):
        self.doc = doc
        self.types = {}
        self.uses_any = False
        for name in sorted((doc.get("components") or {}).get("schemas") or {}):
            self.named(name, (doc["components"]["schemas"] or {})[name])

    def named(self, name, schema):
        tname = type_name(name)
        if tname in self.types:
            return tname
        self.types[tname] = None                     # 순환 참조 자리
        schema = self._flatten(schema)
        if schema.get("enum") and (schema.get("type") in (None, "string")):
            self.types[tname] = {"kind": "enum", "name": tname, "values": [str(v) for v in schema["enum"]]}
        elif schema.get("type") == "object" or "properties" in schema:
            props = schema.get("properties") or {}
            if not props and schema.get("additionalProperties") is not None:
                self.types[tname] = {"kind": "alias", "name": tname, "type": self.ref(schema, tname)}
            else:
                req = set(schema.get("required") or [])
                fields = []
                for pname in props:                 # 선언 순서 — 생성자 인자 순서가 계약과 같다
                    ps = props[pname]
                    fields.append({"name": camel(pname), "json": pname, "type": self.ref(ps, tname + pascal(pname)),
                                   "optional": pname not in req or bool(_resolve(self.doc, ps).get("nullable")),
                                   "doc": str((_resolve(self.doc, ps).get("description") or "")).strip()})
                self.types[tname] = {"kind": "struct", "name": tname, "fields": fields, "doc": str(schema.get("description") or "").strip()}
        else:
            self.types[tname] = {"kind": "alias", "name": tname, "type": self.ref(schema, tname, inline_ok=False)}
        return tname

    def _flatten(self, schema):
        """allOf → 속성 합치기 (한 단계씩 재귀)."""
        schema = _resolve(self.doc, schema) if "$ref" in schema else dict(schema)
        if "allOf" not in schema:
            return schema
        out = {k: v for k, v in schema.items() if k != "allOf"}
        props, req = dict(out.get("properties") or {}), list(out.get("required") or [])
        for part in schema["allOf"]:
            part = self._flatten(part)
            props.update(part.get("properties") or {})
            req += [r for r in (part.get("required") or []) if r not in req]
            out.setdefault("description", part.get("description"))
        out["type"] = "object"
        out["properties"], out["required"] = props, req
        return out

    def ref(self, schema, inline_name, inline_ok=True):
        """스키마 → TypeRef. 인라인 object/enum 은 inline_name 으로 이름 있는 타입을 만든다."""
        if not isinstance(schema, dict):
            self.uses_any = True
            return ("any",)
        if "$ref" in schema:
            return ("ref", _ref_name(schema["$ref"]))
        if "allOf" in schema:
            return ("ref", self.named(inline_name, schema)) if inline_ok else ("any",)
        if "oneOf" in schema or "anyOf" in schema:
            self.uses_any = True
            return ("any",)
        t = schema.get("type")
        if schema.get("enum") and t in (None, "string"):
            return ("ref", self.named(inline_name, schema)) if inline_ok else ("prim", "string")
        if t == "array":
            return ("array", self.ref(schema.get("items") or {}, inline_name + "Item"))
        if t == "object" or "properties" in schema:
            if schema.get("properties"):
                return ("ref", self.named(inline_name, schema)) if inline_ok else ("any",)
            ap = schema.get("additionalProperties")
            if isinstance(ap, dict):
                return ("map", self.ref(ap, inline_name + "Value"))
            self.uses_any = True
            return ("map", ("any",))
        if t == "string":
            return ("prim", "string")
        if t == "integer":
            return ("prim", "int64" if schema.get("format") == "int64" else "int")
        if t == "number":
            return ("prim", "double")
        if t == "boolean":
            return ("prim", "bool")
        self.uses_any = True
        return ("any",)


def _swift_type(t):
    k = t[0]
    if k == "prim":
        return {"string": "String", "int": "Int", "int64": "Int64", "double": "Double", "bool": "Bool"}[t[1]]
    if k == "ref":
        return t[1]
    if k == "array":
        return f"[{_swift_type(t[1])}]"
    if k == "map":
        return f"[String: {_swift_type(t[1])}]"
    return "JSONValue"


def _kt_type(t):
    k = t[0]
    if k == "prim":
        return {"string": "String", "int": "Int", "int64": "Long", "double": "Double", "bool": "Boolean"}[t[1]]
    if k == "ref":
        return t[1]
    if k == "array":
        return f"List<{_kt_type(t[1])}>"
    if k == "map":
        return f"Map<String, {_kt_type(t[1])}>"
    return "JsonElement"


def _kt_serializer(t):
    k = t[0]
    if k == "prim":
        return _kt_type(t) + ".serializer()"
    if k == "ref":
        return f"{t[1]}.serializer()"
    if k == "array":
        return f"ListSerializer({_kt_serializer(t[1])})"
    if k == "map":
        return f"MapSerializer(String.serializer(), {_kt_serializer(t[1])})"
    return "JsonElement.serializer()"


