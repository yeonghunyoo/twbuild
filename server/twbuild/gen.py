def _words(name):
    parts = [p for p in re.split(r"[^0-9A-Za-z]+", str(name)) if p]
    out = []
    for p in parts:
        out += re.findall(r"[A-Z]+(?=[A-Z][a-z])|[A-Z]?[a-z]+|[A-Z]+|\d+", p) or [p]
    return out


def camel(name):
    """snake_case · kebab-case · Header-Name → camelCase 식별자."""
    w = _words(name)
    if not w:
        return "x"
    out = w[0].lower() + "".join(x[:1].upper() + x[1:].lower() if not x.isupper() or len(x) == 1 else x[:1] + x[1:].lower() for x in w[1:])
    return ("_" + out) if out[0].isdigit() else out


def pascal(name):
    w = _words(name)
    out = "".join(x[:1].upper() + x[1:] for x in w) or "X"
    return ("N" + out) if out[0].isdigit() else out


def type_name(name):
    """스키마 이름 → 모델 타입 이름 (PascalCase, 표준 타입과 겹치면 + Model)."""
    n = pascal(name)
    return n + "Model" if n in RESERVED_TYPES else n


def upper_snake(name):
    w = _words(name)
    out = "_".join(x.upper() for x in w) or "X"
    return ("N" + out) if out[0].isdigit() else out


def _sw(n):
    return f"`{n}`" if n in SWIFT_KW else n


def _kt(n):
    return f"`{n}`" if n in KOTLIN_KW else n


def _str_lit(s):
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def _kt_str_lit(s):
    return _str_lit(s).replace("$", "\\$")


