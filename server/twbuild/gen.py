def expected(root, cfg=None):
    """{상대경로: 텍스트} — 지금 계약에서 나와야 하는 플랫폼 코드. 계약이 없으면 빈 dict."""
    if not os.path.isfile(contract.body_path(root)):
        return {}
    cfg = cfg or config.load(root)
    doc = contract.merged(root)
    types = _Types(doc)
    ops = operations(doc, types)
    exs = examples(doc, types, ops)
    pkg = config.app_vars(cfg)["id"]
    paths = _paths(cfg)
    plats = cfg.get("platforms") or []
    out = {}
    if "ios" in plats:
        out[paths["ios_models"]] = _swift_models(types)
        out[paths["ios_client"]] = _swift_client(ops)
    if "android" in plats:
        out[paths["android_models"]] = _kt_models(types, pkg)
        out[paths["android_client"]] = _kt_client(ops, pkg)
        out[paths["android_test"]] = _kt_decode_test(exs, pkg)
    return out


def write(root, cfg=None):
    files = expected(root, cfg)
    for rel, text in files.items():
        util.write_text(os.path.join(root, rel), text)
    return sorted(files)


def drift(root, cfg=None):
    """생성물이 지금 계약과 다른(또는 없는) 파일 목록. 비어 있으면 일치."""
    return [rel for rel, text in expected(root, cfg).items() if util.read_text(os.path.join(root, rel), None) != text]


